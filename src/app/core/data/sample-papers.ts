export function filterSample(query: string): Paper[] {
  const parsed = parseQuery(query);
  if (!parsed.valid || !parsed.ast) {
    return parsed.valid ? [...SAMPLE_PAPERS] : [];
  }
  return SAMPLE_PAPERS.filter((paper) => matchesPaper(paper, parsed.ast!));
}
