const LANG_KEY = 'paperlens.language';

@Injectable({ providedIn: 'root' })
export class LanguageService {
  readonly currentLang = signal<LanguageCode>('en');
  readonly languages = LANGUAGES;

  readonly activeOption = computed(() => {
    return this.languages.find((l) => l.code === this.currentLang()) || this.languages[0];
  });

  constructor() {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem(LANG_KEY) as LanguageCode | null;
      if (saved && TRANSLATIONS[saved]) {
        this.setLanguage(saved);
        return;
      }
    }
  }

  setLanguage(lang: LanguageCode): void {
    if (TRANSLATIONS[lang]) {
      this.currentLang.set(lang);
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem(LANG_KEY, lang);
      }
      if (typeof document !== 'undefined') {
        document.documentElement.lang = lang;
        document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
      }
    }
  }

  t(key: string, fallback = ''): string {
    const lang = this.currentLang();
    const table = TRANSLATIONS[lang] || TRANSLATIONS.en;
    return table[key] ?? TRANSLATIONS.en[key] ?? fallback;
  }
}
